// Emits the JSON Schema bundle and generated TypeScript types from packages/contracts/src/schemas.ts.
// `--check` exits non-zero when committed outputs are stale.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import { schemaBundle } from '../packages/contracts/src/schemas';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const jsonPath = join(root, 'packages/contracts/schemas/pod-contracts.schema.json');
const typesPath = join(root, 'packages/contracts/src/generated/types.ts');
const check = process.argv.includes('--check');

const json = `${JSON.stringify(schemaBundle, null, 2)}\n`;
// json-schema-to-typescript does not understand the ajv-only `discriminator` keyword; strip it for type generation.
const forTypes = JSON.parse(JSON.stringify(schemaBundle, (k, v) => (k === 'discriminator' ? undefined : v)));
const types = await compile(forTypes, 'PodContracts', {
  bannerComment: '/* eslint-disable */\n// GENERATED by scripts/gen-schemas.ts — do not edit by hand.',
  unreachableDefinitions: true,
  additionalProperties: false,
  strictIndexSignatures: true,
  style: { singleQuote: true },
});

const outputs: [string, string][] = [[jsonPath, json], [typesPath, types]];
let stale = false;
for (const [path, content] of outputs) {
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`STALE: ${path} — chạy pnpm gen:schemas`);
      stale = true;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
